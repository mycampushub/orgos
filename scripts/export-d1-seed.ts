/**
 * Exports the local demo database (db/custom.db) to a D1-compatible seed file
 * (cloudflare/seed/seed-demo.sql).
 *
 * WHY THIS EXISTS (the P2023 production bug):
 *   Prisma's binary engine (local dev) stores SQLite DateTime values as
 *   epoch-milliseconds INTEGERS. Prisma's driver-adapter/WASM engine
 *   (Cloudflare Workers via PrismaD1) stores and reads DateTime as
 *   ISO-8601 TEXT ("2026-11-19T08:09:31.454Z") and throws
 *   P2023 "Inconsistent column data" on epoch-ms integers.
 *   A raw dump of the local DB therefore breaks every production route that
 *   SELECTs a row with a DateTime column. This exporter CONVERTS on the way
 *   out: every DATETIME-column value that is a number is rewritten as
 *   new Date(n).toISOString().
 *
 * Table order (FK-safe) is inherited from the previous seed file's
 * DELETE/INSERT sequence, so the output can be applied to D1 directly:
 *   bunx wrangler d1 execute orgos --remote --file cloudflare/seed/seed-demo.sql
 *
 * Run: bun run db:export:seed
 */
import { Database } from 'bun:sqlite'
import { readFileSync, writeFileSync } from 'node:fs'

const LOCAL_DB = 'db/custom.db'
const SEED_PATH = 'cloudflare/seed/seed-demo.sql'

type Col = { name: string; type: string }

function sqlString(v: string): string {
  return `'${v.replace(/'/g, "''")}'`
}

function main() {
  const local = new Database(LOCAL_DB, { readonly: true })

  // Inherit the proven FK-safe ordering from the current seed file.
  const previous = readFileSync(SEED_PATH, 'utf8')
  const deleteOrder = [...previous.matchAll(/DELETE FROM "([A-Za-z]+)"/g)].map((m) => m[1])
  const insertOrder: string[] = []
  for (const m of previous.matchAll(/INSERT INTO "([A-Za-z]+)"/g)) {
    if (!insertOrder.includes(m[1])) insertOrder.push(m[1])
  }
  if (!insertOrder.length) throw new Error('Could not parse table order from existing seed')

  // Tables that exist in the local DB (skip bookkeeping tables).
  const localTables = (
    local.query<{ name: string }>("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '\\_prisma\\_%' ESCAPE '\\'").all()
  ).map((r) => r.name)
  const tables = insertOrder.filter((t) => localTables.includes(t))
  const missing = insertOrder.filter((t) => !localTables.includes(t))
  if (missing.length) console.warn(`[warn] tables in seed but not in local DB (skipped): ${missing.join(', ')}`)

  const parts: string[] = [
    `-- OrgOS demo seed — generated by scripts/export-d1-seed.ts from db/custom.db`,
    `-- D1/Workers-compatible: DateTime columns are emitted as ISO-8601 TEXT`,
    `-- ("YYYY-MM-DDTHH:MM:SS.sssZ"), the canonical format of the Prisma`,
    `-- driver-adapter/WASM engine (epoch-ms integers from the local binary`,
    `-- engine would make every production read fail with P2023).`,
    ``,
    `-- Apply to Cloudflare D1:`,
    `--   bunx wrangler d1 execute orgos --remote --file cloudflare/seed/seed-demo.sql`,
    `-- Idempotent: clears all user tables (reverse FK order) before inserting.`,
    ``,
  ]

  // DELETEs in the inherited (reverse FK) order, filtered to existing tables.
  for (const t of deleteOrder) {
    if (localTables.includes(t)) parts.push(`DELETE FROM "${t}";`)
  }
  parts.push('')

  let totalRows = 0
  for (const table of tables) {
    const cols = local
      .query<{ name: string; type: string }>(`PRAGMA table_info('${table}')`)
      .all()
      .map((c) => ({ name: c.name, type: (c.type || '').toUpperCase() }))
    if (!cols.length) continue
    const colList = cols.map((c) => `"${c.name}"`).join(', ')
    const rows = local
      .query<unknown[]>(`SELECT ${colList} FROM "${table}" ORDER BY rowid`)
      .values() as unknown[][]
    for (const row of rows) {
      const values = row.map((v, i) => {
        const isDatetime = cols[i].type === 'DATETIME'
        if (v === null || v === undefined) return 'NULL'
        if (typeof v === 'number') {
          // binary-engine DateTime storage: epoch-ms integer → ISO-8601 TEXT
          if (isDatetime) return sqlString(new Date(v).toISOString())
          return String(v)
        }
        if (typeof v === 'bigint') {
          if (isDatetime) return sqlString(new Date(Number(v)).toISOString())
          return String(v)
        }
        if (v instanceof Uint8Array) {
          throw new Error(`BLOB value found in ${table}.${cols[i].name} — not expected in this schema`)
        }
        return sqlString(String(v))
      })
      parts.push(`INSERT INTO "${table}" (${colList}) VALUES (${values.join(', ')});`)
      totalRows++
    }
  }

  writeFileSync(SEED_PATH, parts.join('\n') + '\n')
  console.log(`Seed written: ${SEED_PATH}`)
  console.log(`Tables: ${tables.length}, rows: ${totalRows}`)
  console.log(`All DATETIME values converted to ISO-8601 TEXT.`)
}

main()
